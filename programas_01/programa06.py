a, b = 5, 11
x, y = True, False

#Operadores aritméticos
print("-----Operadores Aritméticos-----")
print(f"{a} + {b} = {a+b}")
print(f"{a} - {b} = {a-b}")
print(f"{a} * {b} = {a*b}")
print(f"{a} / {b} = {a/b}")
print(f"{a} // {b} = {a//b}")
print(f"{a} % {b} = {a%b}")
print(f"{a} ** {b} = {a**b}")

#Operadores lógicos
print("\n------Operadores Lógicos-----")
print(f"{x} y {y} -> {x and y}")
print(f"{x} o {y} -> {x or y}")
print(f"Negativo de {x} -> {not x}")
print(f"Negativo de {y} -> {not y}")

#Operadores de comparación con números y booleanos
print("\n-----Operadores comparativos-----")
print(f"{a} == {b} -> {a == b}")
print(f"{a} != {b} -> {a != b}")
print(f"{a} > {b} -> {a > b}")
print(f"{a} < {b} -> {a < b}")
print(f"{a} >= {b} -> {a >= b}")
print(f"{b} >= {a} -> {b >= a}")
print(f"{x} == {y} -> {x == y}")
print(f"{y} == {x} -> {y == x}")

