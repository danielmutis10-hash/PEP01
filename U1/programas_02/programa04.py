print("Cuál es la base y la altura de tu rectángulo? ")
base = float(input("Base: "))
height = float(input("Altura: "))

#Procedimiento para el área del rectángulo
area = base * height

#Procedimiento para el perímetro de un rectángulo
perimeter = 2 * (base + height)

print("El área de su rectángulo es:", area, "y el perímetro es:", perimeter )