print("Dame dos números para calcular su suma, resta, multiplicación, división, módulo, y potencia")
num_1 = float(input("Número 1:"))
num_2 = float(input("Número 1:"))

#Suma
sum = num_1 + num_2

#Resta
rest = num_1 - num_2

#Multiplicación
mult = num_1 * num_2

#División
div = num_1 / num_2

#Módulo
mod = num_1 % num_2

#Potencia
pot = num_1 ** num_2

#Escritura de los procesos
print(" ")
print("Suma:", sum, "\nResta:", rest, "\nMultiplicación:", mult, "\nDivisión:", div, "\nMódulo:", mod, "\nPotencia:", pot)